const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { chromium } = require(process.env.CODEMENTOR_PLAYWRIGHT || "playwright");
process.env.PATH = `${process.env.SystemRoot || "C:\\Windows"}\\System32;${process.env.PATH || ""}`;
const deadline = setTimeout(() => { console.error("Browser verification exceeded four minutes."); process.exit(2); }, 240000);
deadline.unref();
async function main() {
  let browser;
  try { browser = await chromium.launch({ headless: true }); }
  catch { browser = await chromium.launch({ headless: true, channel: "msedge" }); }
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(60000);
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("requestfailed", request => console.error("Request failed:", request.url(), request.failure()?.errorText));
  page.on("console", message => { if (message.type() === "error") console.error("Browser console:", message.text()); });
  page.on("response", response => { if (response.status() >= 400) console.error("HTTP:", response.status(), response.url()); });
  const artifactDir = path.join(__dirname, "../test-artifacts");
  fs.mkdirSync(artifactDir, { recursive: true });
  try {
    await page.goto(process.env.CODEMENTOR_URL || "http://localhost:3000", { waitUntil: "domcontentloaded", timeout: 120000 });
    console.log("Loaded:", page.url());
    await page.getByRole("button", { name: "Beginner", exact: false }).click();
    await page.locator(".monaco-editor .view-lines").waitFor();
    await page.getByRole("button", { name: "Analyze my code" }).click();
    await page.locator(".problem-card").filter({ hasText: "Possible off-by-one error" }).waitFor();
    await page.locator(".squiggly-warning").first().hover({ force: true });
    await page.getByRole("link", { name: "View Problem", exact: true }).waitFor();
    await page.getByRole("link", { name: "View Problem", exact: true }).click();
    await page.getByRole("heading", { name: "What’s wrong?", exact: true }).waitFor();
    console.log("PASS: inline diagnostic hover opens educational problem details");
    await page.getByRole("button", { name: "Give me a hint" }).click();
    await page.locator(".hint").filter({ hasText: "Look carefully" }).waitFor();
    await page.getByRole("button", { name: "Quick Fix", exact: true }).click();
    await page.getByRole("dialog", { name: "Preview Quick Fix" }).waitFor();
    await page.getByRole("button", { name: "Apply Fix", exact: true }).click();
    await page.getByRole("button", { name: "▷ Run", exact: true }).click();
    await page.waitForFunction(() => document.querySelector(".panel-body pre")?.textContent?.trim() === "6", null, { timeout: 60000 });
    console.log("PASS: Analyze → hint → targeted fix → output 6");
    await page.getByRole("button", { name: "Generate Test Cases", exact: false }).first().click();
    await page.getByRole("button", { name: "Run Tests", exact: true }).waitFor();
    await page.getByRole("button", { name: "Run Tests", exact: true }).click();
    await page.getByText("7 / 7 passed", { exact: true }).waitFor();
    console.log("PASS: generated tests pass after correction");
    await page.getByRole("button", { name: "Complexity analysis" }).click();
    await page.locator(".metrics").filter({ hasText: "O(n)" }).waitFor();
    assert.ok((await page.locator(".metrics").innerText()).includes("O(1)"));
    await page.screenshot({ path: path.join(artifactDir, "workspace.png"), fullPage: true });
    await page.getByRole("button", { name: "Toggle Explorer", exact: true }).click();
    await page.reload({ waitUntil: "domcontentloaded" });
    await page.locator(".workspace.sidebar-collapsed").waitFor();
    await page.locator(".monaco-editor .view-lines").waitFor();
    await page.getByRole("button", { name: "▷ Run", exact: true }).click();
    await page.waitForFunction(() => document.querySelector(".panel-body pre")?.textContent?.trim() === "6");
    console.log("PASS: file draft and sidebar state survive refresh");
    await page.getByRole("button", { name: "Toggle Explorer", exact: true }).click();
    await page.getByRole("button", { name: "New file or folder" }).click();
    page.once("dialog", dialog => dialog.accept("src/algorithms/double.ts"));
    await page.getByRole("menuitem", { name: "New file", exact: true }).click();
    await page.getByRole("tab", { name: "double.ts" }).waitFor();
    await page.locator(".monaco-editor").click({ position: { x: 140, y: 50 } });
    await page.keyboard.press("Control+KeyA");
    await page.keyboard.insertText("function double(value: number): number { return value * 2; }\nconsole.log(double(4));");
    await page.getByRole("button", { name: "▷ Run", exact: true }).click();
    await page.waitForFunction(() => document.querySelector(".panel-body pre")?.textContent?.trim() === "8");
    console.log("PASS: nested file creation and TypeScript execution");
    await page.getByRole("button", { name: /TS double.ts/ }).click({ button: "right" });
    page.once("dialog", dialog => dialog.accept("twice.ts"));
    await page.getByRole("menuitem", { name: "Rename", exact: true }).click();
    await page.getByRole("tab", { name: "twice.ts" }).waitFor();
    console.log("PASS: Explorer rename preserves tab and file contents");
    await page.locator(".monaco-editor").click({ position: { x: 140, y: 50 } });
    await page.keyboard.press("Control+KeyA");
    await page.keyboard.insertText("console.log(await Promise.resolve(9));");
    await page.getByRole("button", { name: "▷ Run", exact: true }).click();
    await page.waitForFunction(() => document.querySelector(".panel-body pre")?.textContent?.trim() === "9");
    console.log("PASS: awaited async execution captures output");
    await page.locator(".monaco-editor").click({ position: { x: 140, y: 50 } });
    await page.keyboard.press("Control+KeyA");
    await page.keyboard.insertText("try { await fetch('https://example.invalid/blocked'); } catch { console.log('network blocked'); } console.log(typeof localStorage, typeof document);");
    await page.getByRole("button", { name: "▷ Run", exact: true }).click();
    await page.waitForFunction(() => document.querySelector(".panel-body pre")?.textContent?.trim() === "network blocked\nundefined undefined");
    console.log("PASS: sandbox blocks network and access to app storage and DOM");
    await page.locator(".monaco-editor").click({ position: { x: 140, y: 50 } });
    await page.keyboard.press("Control+KeyA");
    await page.keyboard.insertText("console.log('before'); throw new Error('Student runtime failure');");
    await page.getByRole("button", { name: "▷ Run", exact: true }).click();
    await page.waitForFunction(() => document.querySelector(".panel-body pre")?.textContent?.includes("before\nRuntime: Student runtime failure"));
    console.log("PASS: runtime failures preserve prior output without stack traces");
    await page.locator(".monaco-editor").click({ position: { x: 140, y: 50 } });
    await page.keyboard.press("Control+KeyA");
    await page.keyboard.insertText("while (true) {}");
    await page.getByRole("button", { name: "▷ Run", exact: true }).click();
    await page.getByRole("alert").filter({ hasText: "Execution stopped after 3 seconds" }).waitFor();
    console.log("PASS: infinite loop terminates without freezing editor");
    await page.getByRole("button", { name: "▷ Run", exact: true }).click();
    await page.getByRole("button", { name: "Cancel run", exact: true }).click();
    await page.getByRole("alert").filter({ hasText: /cancel|abort/i }).waitFor();
    console.log("PASS: execution can be cancelled");
    assert.deepEqual(errors, []);
  } catch (error) {
    console.error("Failed:", error.message);
    await page.screenshot({ path: path.join(artifactDir, "failure.png"), fullPage: true, timeout: 10000 }).catch(() => {});
    fs.writeFileSync(path.join(artifactDir, "failure.txt"), await page.locator("body").innerText({ timeout: 10000 }).catch(() => "No DOM"));
    console.error("Browser errors:", errors);
    throw error;
  } finally { await Promise.race([browser.close(), new Promise(resolve => setTimeout(resolve, 5000))]); }
}
main().then(() => process.exit(0)).catch(error => { console.error(error); process.exit(1); });
