const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { chromium } = require(process.env.CODEMENTOR_PLAYWRIGHT || "playwright");
process.env.PATH = `${process.env.SystemRoot || "C:\\Windows"}\\System32;${process.env.PATH || ""}`;
async function main() {
  let browser;
  try { browser = await chromium.launch({ headless: true }); } catch { browser = await chromium.launch({ headless: true, channel: "msedge" }); }
  const context = await browser.newContext({ viewport: { width: 1560, height: 1050 }, permissions: ["clipboard-read", "clipboard-write"] });
  const page = await context.newPage();
  page.setDefaultTimeout(45000);
  const errors = [], requests = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("dialog", async dialog => { errors.push(`Native dialog: ${dialog.type()}`); await dialog.dismiss(); });
  page.on("request", request => { if (request.url().endsWith("/api/mentor") && request.method() === "POST") requests.push(request.postDataJSON()); });
  const artifacts = path.resolve("test-artifacts"); fs.mkdirSync(artifacts, { recursive: true });
  let frame;
  async function ready() { await page.waitForFunction(() => document.querySelector(".real-workbench")?.contentWindow?.codeMentorWorkbench, undefined, { timeout: 90000 }); frame = page.frames().find(item => item.url().endsWith("/ide/index.html")); assert.ok(frame); }
  async function state() { return frame.evaluate(() => { const instance = window.codeMentorWorkbench.editor(); const range = instance.getSelection(); return { code: instance.getValue(), selected: instance.getModel().getValueInRange(range), uri: instance.getModel().uri.toString() }; }); }
  async function command(title) { await frame.evaluate(() => window.codeMentorWorkbench.editor().focus()); await page.keyboard.press("F1"); const input = frame.locator(".quick-input-widget input"); await input.fill(`>${title}`); await page.keyboard.press("Enter"); }
  try {
    await page.goto(process.env.CODEMENTOR_URL || "http://localhost:3000");
    await page.getByRole("button", { name: "Beginner", exact: false }).click();
    await ready();
    await frame.locator(".monaco-workbench").waitFor();
    assert.equal(await frame.locator(".part.sidebar").count(), 1);
    const initial = (await state()).code;
    const positions = await frame.evaluate(() => { const editor = window.codeMentorWorkbench.editor(); const rect = editor.getDomNode().getBoundingClientRect(); const first = editor.getScrolledVisiblePosition({ lineNumber: 1, column: 1 }); const last = editor.getScrolledVisiblePosition({ lineNumber: 7, column: 2 }); return { rect: { x: rect.x, y: rect.y }, first, last }; });
    const bounds = await page.locator(".real-workbench").boundingBox();
    await page.mouse.move(bounds.x + positions.rect.x + positions.first.left, bounds.y + positions.rect.y + positions.first.top + 8);
    await page.mouse.down();
    await page.mouse.move(bounds.x + positions.rect.x + positions.last.left, bounds.y + positions.rect.y + positions.last.top + 8, { steps: 30 });
    await page.mouse.up();
    assert.equal((await state()).selected, initial.split("\n").slice(0, 7).join("\n"));
    await frame.getByRole("button", { name: "Submit for Review", exact: true }).click();
    await frame.locator(".review-status").getByText("Analysis current · v1", { exact: true }).waitFor();
    assert.equal(requests[0].selection.text, initial.split("\n").slice(0, 7).join("\n"));
    assert.equal((await state()).selected, requests[0].selection.text);
    await frame.locator(".problem-card").first().waitFor();
    await frame.getByRole("button", { name: "Give me a hint", exact: false }).click();
    await frame.locator(".hint").first().waitFor();
    await frame.getByRole("button", { name: "Quick Fix", exact: true }).click();
    await page.getByRole("button", { name: "Apply Fix", exact: true }).click();
    await frame.locator(".review-status").getByText("Code changed · Analysis outdated", { exact: true }).waitFor();
    assert.ok((await state()).code.includes("i < numbers.length"));
    await frame.getByRole("button", { name: "Submit for Review", exact: true }).click();
    await frame.locator(".review-status").getByText("Analysis current · v2", { exact: true }).waitFor();
    await frame.locator(".mentor .coming").getByRole("button", { name: "Generate Test Cases", exact: false }).click();
    await frame.locator(".test-case").first().waitFor();
    await frame.getByRole("button", { name: "Run Tests", exact: true }).click();
    await frame.locator(".panel-body").getByText(/\d+ \/ \d+ passed/).waitFor();
    const passed = await frame.locator(".panel-body").getByText(/\d+ \/ \d+ passed/).innerText();
    const counts = passed.match(/(\d+) \/ (\d+)/); assert.equal(counts[1], counts[2]);
    await frame.locator(".mentor .coming").getByRole("button", { name: "Complexity analysis", exact: false }).click();
    await frame.locator(".complexity-content").getByText("O(n)", { exact: true }).first().waitFor();
    await frame.waitForFunction(() => !document.querySelector(".mentor>.primary")?.disabled);
    await command("CodeMentor: Run Current File");
    await frame.locator(".output-view .view-lines").getByText("6", { exact: true }).first().waitFor();
    await frame.evaluate(() => window.codeMentorWorkbench.editor().focus());
    await page.keyboard.press("Control+KeyA"); assert.equal((await state()).selected, (await state()).code);
    await page.keyboard.press("Control+KeyC"); assert.equal((await page.evaluate(() => navigator.clipboard.readText())).replace(/\r\n/g, "\n"), (await state()).code.replace(/\r\n/g, "\n"));
    await command("View: Toggle Primary Side Bar Visibility");
    await command("View: Toggle Primary Side Bar Visibility");
    console.log("PASS: native selection, versioned diagnostics, hints, guarded fix, generated tests, complexity, Output, palette and clipboard");
    await frame.locator('.part.sidebar [aria-label="New File..."]:visible').first().click();
    let name = frame.locator(".explorer-item .monaco-inputbox input");
    await name.fill("src/utils.ts"); await name.press("Enter");
    await page.waitForFunction(() => JSON.parse(localStorage.getItem("codementor-workspace-v1")).files.some(file => file.path === "src/utils.ts"));
    await frame.waitForFunction(() => window.codeMentorWorkbench.editor().getModel().uri.path.endsWith("/src/utils.ts"));
    await frame.evaluate(() => window.codeMentorWorkbench.editor().focus());
    await page.keyboard.type("export const value = 7;");
    await page.keyboard.press("Control+KeyS");
    await page.waitForFunction(() => JSON.parse(localStorage.getItem("codementor-workspace-v1")).files.find(file => file.path === "src/utils.ts")?.saved === "export const value = 7;");
    await frame.locator(".explorer-item").filter({ hasText: "utils.ts" }).last().click(); await page.keyboard.press("F2");
    name = frame.locator(".explorer-item .monaco-inputbox input"); await name.fill("index.test.ts"); await name.press("Enter");
    await page.waitForFunction(() => JSON.parse(localStorage.getItem("codementor-workspace-v1")).files.some(file => file.path === "src/index.test.ts"));
    await frame.waitForFunction(() => !document.querySelector('.tabs-container')?.textContent.includes('utils.ts'));
    await page.reload(); await ready();
    assert.ok((await state()).uri.endsWith("/src/index.test.ts"));
    assert.equal((await state()).code, "export const value = 7;");
    await frame.locator('.part.sidebar [aria-label="New Folder..."]:visible').first().click();
    name = frame.locator(".explorer-item .monaco-inputbox input"); await name.fill("nested"); await name.press("Enter");
    await page.waitForFunction(() => JSON.parse(localStorage.getItem("codementor-workspace-v1")).files.some(file => file.path === "src/nested"));
    await frame.locator('.part.sidebar [aria-label="New File..."]:visible').first().click();
    name = frame.locator(".explorer-item .monaco-inputbox input"); await name.fill("scratch.js"); await name.press("Enter");
    await frame.waitForFunction(() => window.codeMentorWorkbench.editor().getModel().uri.path.endsWith("/src/nested/scratch.js"));
    await frame.evaluate(() => window.codeMentorWorkbench.editor().focus()); await page.keyboard.type("const unsaved = 1;");
    await frame.locator(".explorer-item").filter({ hasText: "nested" }).last().click(); await page.keyboard.press("F2");
    name = frame.locator(".explorer-item .monaco-inputbox input"); await name.fill("renamed"); await name.press("Enter");
    await page.waitForFunction(() => JSON.parse(localStorage.getItem("codementor-workspace-v1")).files.some(file => file.path === "src/renamed/scratch.js" && file.content === "const unsaved = 1;"));
    await frame.waitForFunction(() => window.codeMentorWorkbench.editor()?.getModel().uri.path.endsWith("/src/renamed/scratch.js"));
    await frame.locator(".explorer-item").filter({ hasText: "renamed" }).last().click(); await page.keyboard.press("Delete");
    await frame.getByText(/You are deleting a folder.*unsaved changes/).waitFor();
    await frame.getByRole("button", { name: "Cancel", exact: true }).click();
    assert.equal((await state()).code, "const unsaved = 1;");
    await page.keyboard.press("Delete");
    await frame.getByRole("button", { name: /Delete/ }).click();
    await page.waitForFunction(() => !JSON.parse(localStorage.getItem("codementor-workspace-v1")).files.some(file => file.path.startsWith("src/renamed")));
    await frame.waitForFunction(() => !document.querySelector('.tabs-container')?.textContent.includes('scratch.js'));
    console.log("PASS: native folder creation, nested unsaved rename, deletion warning, cancel and recursive tab cleanup");
    await frame.locator(".explorer-item").filter({ hasText: "index.test.ts" }).last().click();
    await frame.getByRole("button", { name: "Version History", exact: true }).click();
    await page.getByRole("dialog", { name: "Version History" }).waitFor();
    const versions = await page.evaluate(() => JSON.parse(localStorage.getItem("codementor-versions-v1")));
    await page.getByLabel("Compare to version").selectOption(versions[0].id);
    await page.getByRole("button", { name: "Restore v1", exact: true }).click();
    await page.getByRole("button", { name: "Cancel restore", exact: true }).click();
    assert.equal((await state()).code, "export const value = 7;");
    await page.getByRole("button", { name: "Restore v1", exact: true }).click();
    await page.getByRole("button", { name: "Preserve drafts and restore", exact: true }).click();
    await page.getByRole("dialog", { name: "Version History" }).waitFor({ state: "hidden" });
    await frame.waitForFunction(() => window.codeMentorWorkbench.editor()?.getValue().includes("i <= numbers.length"));
    assert.equal((await state()).code, initial);
    assert.ok(!await frame.locator('.tabs-container').innerText().then(text => text.includes("utils.ts") || text.includes("index.test.ts")));
    console.log("PASS: native version restore preserves a backup and replaces working copies without orphan tabs");
    assert.deepEqual(errors, []);
    await page.screenshot({ path: path.join(artifacts, "workbench-success.png"), fullPage: true });
    console.log("Native workbench smoke passed: real Explorer, selection, versioned mentor, fixes, sandbox tests, complexity, palette, creation, save, rename and refresh.");
  } catch (error) {
    await page.screenshot({ path: path.join(artifacts, "workbench-failure.png"), fullPage: true }).catch(() => {});
    fs.writeFileSync(path.join(artifacts, "workbench-failure.txt"), JSON.stringify({ error: error.message, errors, parent: await page.locator("body").innerText().catch(() => ""), frame: frame ? await frame.locator("body").innerText().catch(() => "") : "" }, null, 2));
    throw error;
  } finally { await browser.close(); }
}
main().then(() => process.exit(0)).catch(error => { console.error(error); process.exit(1); });
