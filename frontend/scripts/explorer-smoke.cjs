const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { chromium } = require(process.env.CODEMENTOR_PLAYWRIGHT || "playwright");
process.env.PATH = `${process.env.SystemRoot || "C:\\Windows"}\\System32;${process.env.PATH || ""}`;
const deadline = setTimeout(() => process.exit(2), 240000);
deadline.unref();
async function main() {
  let browser;
  try { browser = await chromium.launch({ headless: true }); }
  catch { browser = await chromium.launch({ headless: true, channel: "msedge" }); }
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(20000);
  const errors = [];
  const dialogs = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("dialog", async dialog => { dialogs.push(dialog.type()); await dialog.dismiss(); });
  const workspace = () => page.evaluate(() => JSON.parse(localStorage.getItem("codementor-workspace-v1")));
  const tree = name => page.getByRole("treeitem", { name, exact: true });
  const input = kind => page.getByRole("textbox", { name: `New ${kind} name`, exact: true });
  async function start(kind, parent) {
    if (parent) await tree(parent).click({ button: "right" });
    else await page.locator(".explorer-root").click({ button: "right" });
    await page.getByRole("menuitem", { name: `New ${kind}`, exact: true }).click();
    assert.equal(await input(kind).evaluate(element => element === document.activeElement), true);
  }
  async function create(name, kind = "file", parent) { await start(kind, parent); await input(kind).fill(name); await input(kind).press("Enter"); await tree(name.trim().split("/").at(-1)).first().waitFor(); }
  async function rename(name, next) { await tree(name).click({ button: "right" }); await page.getByRole("menuitem", { name: "Rename", exact: true }).click(); const field = page.getByRole("textbox", { name: `Rename ${name.includes(".") ? "file" : "folder"}`, exact: true }); await field.fill(next); await field.press("Enter"); }
  async function requestDelete(name) { await tree(name).click({ button: "right" }); await page.getByRole("menuitem", { name: "Delete", exact: true }).click(); await page.getByRole("dialog", { name: /^Delete/ }).waitFor(); }
  async function editorState() { await page.locator(".monaco-editor .view-lines").waitFor(); return page.evaluate(() => new Promise((resolve, reject) => { const timer = setTimeout(() => reject(new Error("Editor inspection timed out")), 10000); window.require(["vs/editor/editor.main"], monaco => { clearTimeout(timer); const instance = monaco.editor.getEditors().find(editor => editor.getModel()); resolve({ uri: instance.getModel().uri.toString(), code: instance.getValue(), selection: instance.getSelection().toString(), language: instance.getModel().getLanguageId() }); }, reject); })); }
  try {
    await page.goto(process.env.CODEMENTOR_URL || "http://localhost:3000/?classic", { waitUntil: "domcontentloaded" });
    await page.getByRole("button", { name: "Beginner", exact: false }).click();
    await page.locator(".monaco-editor .view-lines").waitFor();
    await page.getByRole("button", { name: "New file or folder" }).click();
    await page.getByRole("menuitem", { name: "New file", exact: true }).click();
    assert.equal(await input("file").evaluate(element => element === document.activeElement), true);
    await input("file").press("Enter");
    await page.getByRole("alert").filter({ hasText: "Enter a name" }).waitFor();
    for (const name of ["../bad.ts", "bad:name.ts", "CON.ts", " "]) {
      await input("file").fill(name);
      await input("file").press("Enter");
      assert.equal((await workspace()).files.length, 1);
    }
    await input("file").fill(" utils.ts ");
    await page.keyboard.press("Enter");
    await page.keyboard.press("Enter");
    await page.getByRole("tab", { name: "utils.ts", exact: true }).waitFor();
    assert.equal((await workspace()).files.filter(file => file.path === "utils.ts").length, 1);
    console.log("PASS: inline autofocus, empty/invalid validation, trim, repeated Enter, and automatic tab opening");
    await start("file"); await input("file").fill("utils.ts"); await input("file").press("Enter");
    await page.getByRole("alert").filter({ hasText: "already exists" }).waitFor();
    assert.equal(await input("file").inputValue(), "utils.ts");
    await input("file").press("Escape");
    await start("folder"); await input("folder").fill("utils.ts"); await input("folder").press("Enter");
    await page.getByRole("alert").filter({ hasText: "already exists" }).waitFor();
    await input("folder").press("Escape");
    const beforeCancel = await workspace();
    await start("file"); await input("file").fill("cancelled.ts"); await input("file").press("Escape");
    assert.deepEqual((await workspace()).files, beforeCancel.files);
    await start("file"); await input("file").fill("blur.ts"); await page.locator(".explorer-root").click();
    assert.equal(await input("file").count(), 0);
    console.log("PASS: duplicate file/folder errors preserve input; Escape and blur cancel safely");
    await create("src", "folder");
    assert.equal(await tree("src").getAttribute("aria-expanded"), "true");
    assert.equal(await tree("src").getAttribute("aria-selected"), "true");
    await tree("src").click();
    assert.equal(await tree("src").getAttribute("aria-expanded"), "false");
    await create("algorithms/deep/utils.ts", "file", "src");
    assert.equal(await tree("src").getAttribute("aria-expanded"), "true");
    assert.equal((await workspace()).files.filter(file => file.path.endsWith("utils.ts")).length, 2);
    await page.locator(".monaco-editor").click({ position: { x: 150, y: 50 } });
    await page.keyboard.press("Control+KeyA");
    await page.keyboard.insertText("const answer = 42;\nconsole.log(answer);");
    await page.keyboard.press("Control+Home");
    await page.keyboard.press("ArrowRight");
    const beforeRename = await editorState();
    const nestedFile = (await workspace()).files.find(file => file.path === "src/algorithms/deep/utils.ts");
    await page.getByTitle("src/algorithms/deep/utils.ts", { exact: true }).click({ button: "right" });
    await page.getByRole("menuitem", { name: "Rename", exact: true }).click();
    const renameField = page.getByRole("textbox", { name: "Rename file", exact: true });
    assert.equal(await renameField.evaluate(element => element.value.slice(element.selectionStart, element.selectionEnd)), "utils");
    await renameField.fill("index.test.js"); await renameField.press("Enter");
    await tree("index.test.js").waitFor();
    const afterRename = await editorState();
    assert.equal(afterRename.uri, beforeRename.uri);
    assert.equal(afterRename.code, beforeRename.code);
    assert.equal(afterRename.selection, beforeRename.selection);
    assert.equal(afterRename.language, "javascript");
    await rename("src", "lib");
    await tree("lib").waitFor();
    const moved = (await workspace()).files.find(file => file.id === nestedFile.id);
    assert.equal(moved.path, "lib/algorithms/deep/index.test.js");
    assert.equal(moved.content, beforeRename.code);
    assert.equal(moved.saved, "");
    await page.getByRole("tab", { name: "index.test.js •", exact: true }).waitFor();
    console.log("PASS: nested creation, automatic expansion, same filename in different folders, rename preserves draft/model/cursor/tabs");
    await create("other.ts", "file", "deep");
    console.log("Checking conflicting rename and restoration");
    await tree("other.ts").focus(); await page.keyboard.press("F2");
    await page.getByRole("textbox", { name: "Rename file", exact: true }).fill("index.test.js");
    await page.getByRole("textbox", { name: "Rename file", exact: true }).press("Enter");
    await page.getByRole("alert").filter({ hasText: "already exists" }).waitFor();
    await page.getByRole("textbox", { name: "Rename file", exact: true }).press("Escape");
    await tree("other.ts").waitFor();
    console.log("Rename conflict cancelled");
    await tree("lib").click();
    await page.reload({ waitUntil: "domcontentloaded" });
    await tree("lib").waitFor();
    assert.equal(await tree("lib").getAttribute("aria-expanded"), "false");
    assert.equal(await tree("index.test.js").count(), 0);
    await tree("lib").focus(); await page.keyboard.press("ArrowRight");
    await tree("index.test.js").waitFor();
    console.log("Collapsed folder restored and expanded after reload");
    await tree("index.test.js").click();
    assert.equal((await editorState()).code, beforeRename.code);
    console.log("PASS: conflicting rename cancellation, keyboard expansion, folder expansion and unsaved content survive refresh");
    await requestDelete("lib");
    const dialog = page.getByRole("dialog", { name: "Delete folder?", exact: true });
    assert.match(await dialog.innerText(), /all 4 items inside/);
    assert.match(await dialog.innerText(), /unsaved changes/);
    assert.equal(await dialog.getByRole("button", { name: "Cancel", exact: true }).evaluate(element => element === document.activeElement), true);
    await page.keyboard.press("Shift+Tab");
    assert.equal(await dialog.getByRole("button", { name: "Delete", exact: true }).evaluate(element => element === document.activeElement), true);
    await page.keyboard.press("Escape");
    assert.ok((await workspace()).files.some(file => file.path === "lib"));
    await requestDelete("lib"); await dialog.getByRole("button", { name: "Delete", exact: true }).click();
    assert.equal((await workspace()).files.some(file => file.path.startsWith("lib")), false);
    assert.equal(await page.getByRole("tab", { name: /index.test|other.ts/ }).count(), 0);
    assert.ok((await workspace()).activeId);
    await page.reload({ waitUntil: "domcontentloaded" });
    assert.equal((await workspace()).files.some(file => file.path.startsWith("lib")), false);
    await requestDelete("utils.ts");
    await page.getByRole("dialog", { name: "Delete file?", exact: true }).getByRole("button", { name: "Cancel", exact: true }).click();
    await tree("utils.ts").waitFor();
    console.log("PASS: custom delete modal, focus trap, nested/unsaved warnings, cancellation, descendant/tab cleanup and persisted deletion");
    await page.locator(".explorer-root").dispatchEvent("contextmenu", { clientX: 1438, clientY: 998 });
    const bounds = await page.getByRole("menu", { name: "Explorer actions" }).boundingBox();
    assert.ok(bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= 1440 && bounds.y + bounds.height <= 1000);
    await page.keyboard.press("Escape");
    assert.equal(await page.getByRole("menu").count(), 0);
    await page.getByRole("button", { name: "New file or folder" }).click();
    await page.locator("header strong").click();
    assert.equal(await page.getByRole("menu").count(), 0);
    await page.getByRole("button", { name: "New file or folder" }).click();
    await page.getByRole("button", { name: "New file or folder" }).click();
    assert.ok(await page.getByRole("menu").count() <= 1);
    await page.keyboard.press("Escape");
    await page.getByRole("button", { name: "Toggle Explorer", exact: true }).click();
    await page.reload({ waitUntil: "domcontentloaded" });
    await page.locator(".workspace.sidebar-collapsed").waitFor();
    assert.deepEqual(dialogs, []);
    assert.deepEqual(errors, []);
    console.log("PASS: viewport-safe menus, outside/Escape dismissal, persistent sidebar and zero native dialogs/runtime errors");
    await page.getByRole("button", { name: "Toggle Explorer", exact: true }).click();
    await requestDelete("utils.ts");
    await page.getByRole("dialog", { name: "Delete file?", exact: true }).getByRole("button", { name: "Delete", exact: true }).click();
    await requestDelete("solution.js");
    await page.getByRole("dialog", { name: "Delete file?", exact: true }).getByRole("button", { name: "Delete", exact: true }).click();
    assert.deepEqual((await workspace()).files, []);
    await page.getByRole("button", { name: "New File", exact: true }).click();
    await input("file").fill("restart.ts"); await input("file").press("Enter");
    await page.getByRole("tab", { name: "restart.ts", exact: true }).waitFor();
    console.log("PASS: deleting the last file leaves a usable workspace; empty-editor creation uses inline UI");
    await page.addInitScript(() => localStorage.setItem("codementor-workspace-v1", '{"files":[{"path":"missing/invalid.ts"}]}'));
    await page.reload({ waitUntil: "domcontentloaded" });
    await tree("solution.js").waitFor();
    await page.getByRole("alert").filter({ hasText: "Saved workspace could not be restored" }).waitFor();
    assert.ok((await editorState()).code.includes("function sum(numbers)"));
    assert.deepEqual(dialogs, []);
    assert.deepEqual(errors, []);
    console.log("PASS: corrupted workspace recovers safely with an in-app error and no native dialogs");
    fs.mkdirSync(path.join(__dirname, "../test-artifacts"), { recursive: true });
    await start("file");
    await input("file").fill("utils.ts");
    await page.screenshot({ path: path.join(__dirname, "../test-artifacts/explorer.png"), fullPage: true });
    await input("file").press("Escape");
  } catch (error) {
    fs.mkdirSync(path.join(__dirname, "../test-artifacts"), { recursive: true });
    await page.screenshot({ path: path.join(__dirname, "../test-artifacts/explorer-failure.png"), fullPage: true }).catch(() => {});
    console.error("Browser runtime errors:", errors);
    throw error;
  } finally { await Promise.race([browser.close(), new Promise(resolve => setTimeout(resolve, 5000))]); }
}
main().then(() => process.exit(0)).catch(error => { console.error(error); process.exit(1); });
